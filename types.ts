
export type ViewState = 'DASHBOARD' | 'ACTIVITY' | 'VAULT' | 'REPORTS' | 'SETTINGS' | 'CREATOR' | 'CLIENT_PREVIEW' | 'TRASH' | 'BRANDING';

export interface FileMetadata {
    resolution?: string;
    colorProfile?: string;
    duration?: string;
    pages?: number;
    dpi?: number;
    software?: string;
    hash?: string; // SHA-256 for verification
}

export interface FileAsset {
    id: string;
    name: string;
    size: string;
    type: 'image' | 'video' | 'pdf' | 'doc' | 'archive' | 'audio' | 'design';
    locked: boolean;
    previewUrl?: string; // For the low-res watermark or thumb
    externalUrl?: string; // BYOS: The real file link (Dropbox/Drive) - Input by creator
    downloadUrl?: string; // SIGNED URL: Generated by server only after payment
    storageProvider?: 'native' | 'drive' | 'dropbox' | 'onedrive' | 'box' | 'wetransfer' | 's3';
    version: number;
    uploadDate: string;
    tag?: string;
    metadata?: FileMetadata;
    milestoneId?: string; // NEW: Link file to specific milestone
    includeInLibrary?: boolean;
    importSourceUrl?: string; // Original URL entered by creator (pre-normalisation) — used for dup detection
    folderName?: string;      // Folder label when file was imported as part of a folder link
}

export interface Milestone {
    id: string;
    title: string;
    amount: number;
    status: 'paid' | 'pending' | 'locked';
    dueDate: string;
}

export interface CredentialBlock {
    id: string;
    serviceName: string;
    username?: string;
    password?: string; // Stored securely (mocked encryption)
    notes?: string;
}

export interface ProjectTheme {
    wallpaper: string;
    name: string;
    brightness: 'dark' | 'light';
    pattern?: 'lines' | 'dots' | 'grid' | 'waves' | 'none' | 'plus' | 'circuit' | 'rhombus';
    showGrain?: boolean;
    brandPrimary?: string;
    brandAccent?: string;
    brandLogoUrl?: string;
    layout?: 'default' | 'billboard' | 'masonry' | 'cinema' | 'journal' | 'split' | 'portfolio' | 'deck' | 'modeler' | 'studio';
    lightbox?: 'default' | 'pro' | 'workstation' | 'canvas' | 'sheet';
}

export interface ProjectPaymentMethods {
    stripeEnabled?: boolean;
    venmo?: string;
    cashapp?: string;
    paypal?: string;
    zelle?: string;
    bankInfo?: string;
}

// Added 'payment_verification' status for manual handshake
export type ProjectStatus = 'draft' | 'awaiting_signature' | 'awaiting_payment' | 'payment_verification' | 'paid' | 'completed';

export interface AccessConfig {
    mode: 'permanent' | '7_day' | 'one_time';
    expiresAt?: string; // ISO String
    viewCount?: number;
    scopeCreepPaused?: boolean;
    pauseReason?: string;
}

export interface Project {
    id: string;
    name: string;
    description: string;
    client: { name: string, email: string, phone?: string, company?: string, avatar?: string };
    amount: number;
    status: ProjectStatus;
    createdAt: string;
    dueDate: string;
    files: FileAsset[];
    milestones: Milestone[];
    credentials?: CredentialBlock[]; // NEW: Credential Vault
    requiresSignature: boolean;
    enableTips?: boolean;
    paymentMethods?: ProjectPaymentMethods;
    useMilestones?: boolean;
    clientLink: string;
    type?: 'web' | 'brand' | 'video';
    theme?: ProjectTheme;
    message?: string;
    enableClientLibrary?: boolean;
    accessConfig?: AccessConfig;
    clientViewedAt?: string; // ISO String — set when client first opens link
    showWatermark?: boolean;       // default true — toggle the tiled watermark text overlay on protected previews
    showProtectedLabel?: boolean;  // default true — toggle the "Protected Preview" card on locked images
    revisionRequests?: RevisionRequest[];
}

export interface AgencySettings {
    cname: string;
    cnameVerified: boolean;
    customSmtp: boolean;
    removeBranding: boolean;
    dataRetentionDays: number;
    supportEmail: string;
    brandKits?: Record<string, {
        primaryColor?: string;
        accentColor?: string;
        logoUrl?: string;
        notes?: string;
        updatedAt?: string;
    }>;
}

export interface StorageSettings {
    /**
     * Production posture:
     * - Platform storage (private R2) is handled via server-issued presigned URLs.
     * - Do not store any cloud OAuth tokens or S3/R2 secret keys in the browser or in `profiles.storage_settings`.
     */
    mode: 'platform' | 'drive' | 's3';

    // Optional non-sensitive BYOS label (links-only workflow; no OAuth tokens stored client-side).
    byosDriveProvider?: 'google' | 'dropbox' | 'onedrive';
    byosDriveAccountLabel?: string;

    // Optional non-sensitive S3/R2 metadata (links-only workflow; no secret keys stored client-side).
    s3Provider?: 'aws' | 'r2' | 'custom';
    s3Bucket?: string;
    s3Region?: string;
    s3Endpoint?: string;
    s3PublicBaseUrl?: string;
}

export interface RevisionRequest {
    id: string;
    fileId?: string;
    fileName?: string;
    message: string;
    authorName: string;
    createdAt: string;
    status: 'open' | 'resolved';
    x?: number; // Pin X coordinate (percentage 0-1)
    y?: number; // Pin Y coordinate (percentage 0-1)
}

export interface ProfilePreferences {
    emailAlerts: boolean;
    pushNotifs: boolean;
    twoFactor: boolean;
    biometric: boolean;
    soundEffects?: boolean;
}

export interface UserProfile {
    id: string;
    name: string;
    email: string;
    avatar: string;
    role: string;
    subdomain: string;
    // Stripe Connect Configuration
    stripeConnect?: {
        accountId: string;     // Connected account ID (acct_...)
        connected: boolean;
        displayName: string;   // Business name from Stripe
        chargesEnabled: boolean;
        payoutsEnabled: boolean;
    };
    paymentMethods: {
        venmo?: string;
        cashapp?: string;
        paypal?: string;
        zelle?: string;
        bankInfo?: string;
    };
    agencySettings?: AgencySettings;
    storageSettings?: StorageSettings;
    profilePreferences?: ProfilePreferences;
}
